export const formatRupiah = (val) => {
  if (!val) return 'Rp 0';
  if (val >= 1000000000) {
    return `Rp ${(val / 1000000000).toFixed(2)} M`;
  }
  if (val >= 1000000) {
    return `Rp ${(val / 1000000).toFixed(1)} Jt`;
  }
  return `Rp ${val.toLocaleString('id-ID')}`;
};

